/**
 * Write the download list for the Fresh Moves glasses fix page.
 *
 * The list is generated from the zips that actually exist on disk rather than
 * written by hand, so the page cannot advertise a version that was never
 * built. Each entry records the pack format the zip was built with, which is
 * the number a user needs to match against their game version.
 *
 * Usage: node scripts/fresh_moves_site.mjs [builds-dir] [out-file]
 */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
import os from 'node:os';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const builds_dir = path.resolve(process.argv[2] ?? path.join(root, 'fresh-moves-glasses', 'builds'));
const out_file = path.resolve(process.argv[3] ?? path.join(root, 'publisher', 'fresh-moves', 'site.js'));

if (!fs.existsSync(builds_dir)) {
	throw new Error(`[freshmoves] ${builds_dir} does not exist; run scripts/build_packs.mjs first`);
}

const PREFIX = 'JustExpressions-FreshMoves-glasses-';

/** Read the pack format out of a zip without trusting the file name. */
function pack_format(zip) {
	const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'fmt-'));
	try {
		execFileSync('unzip', ['-qo', zip, 'pack.mcmeta', '-d', tmp]);
		const meta = JSON.parse(fs.readFileSync(path.join(tmp, 'pack.mcmeta'), 'utf8'));
		return meta.pack?.pack_format ?? null;
	} finally {
		fs.rmSync(tmp, {recursive: true, force: true});
	}
}

/** Sort newest game version first, by the numbers in the name. */
function version_key(version) {
	const parts = version.split('.').map(Number);
	return parts;
}
function compare(a, b) {
	const pa = version_key(a);
	const pb = version_key(b);
	for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
		const x = pa[i] ?? 0;
		const y = pb[i] ?? 0;
		if (x !== y) return y - x;
	}
	return 0;
}

const zips = fs.readdirSync(builds_dir)
	.filter(name => name.startsWith(PREFIX) && name.endsWith('.zip'))
	.map(name => ({
		name,
		version: name.slice(PREFIX.length, -'.zip'.length),
		bytes: fs.statSync(path.join(builds_dir, name)).size,
	}));

if (zips.length === 0) {
	throw new Error(`[freshmoves] no packs matching ${PREFIX}*.zip in ${builds_dir}`);
}

const entries = zips
	.sort((a, b) => compare(a.version, b.version))
	.map(zip => ({
		version: zip.version,
		// Served from the repository itself: the files are committed, so this
		// URL works without a GitHub login, unlike an Actions artifact.
		href: `/download/fresh-moves/${zip.name}`,
		file: zip.name,
		kilobytes: Math.round(zip.bytes / 1024),
		pack_format: pack_format(path.join(builds_dir, zip.name)),
	}));

const payload = {
	title: 'Just Expressions + Fresh Moves glasses fix',
	builds: entries,
};
fs.mkdirSync(path.dirname(out_file), {recursive: true});
fs.writeFileSync(
	out_file,
	'// Generated by scripts/fresh_moves_site.mjs. Do not edit.\n' +
	`window.FRESH_MOVES = ${JSON.stringify(payload, null, '\t')};\n`
);
console.log(`[freshmoves] wrote ${entries.length} entries to ${path.relative(root, out_file)}`);
