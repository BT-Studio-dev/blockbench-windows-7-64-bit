/**
 * Write `build-info.json` and `publisher/site.js` from the same data.
 *
 * The Rust function embeds `build-info.json` at compile time and the landing
 * page loads `publisher/site.js`, so the version, commit and download links can
 * never disagree between the two.
 *
 * Both files are generated, so they are gitignored. Run this before
 * `npm run build-web` and before deploying:
 *
 *   node scripts/site.mjs
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = fileURLToPath(import.meta.url);
const root = path.resolve(path.dirname(here), '..');

const GITHUB_REPO = 'BT-Studio-dev/blockbench-windows-7-64-bit';
const WORKFLOW_FILE = 'build-windows7.yml';

function git(args) {
	try {
		return execFileSync('git', args, {cwd: root, encoding: 'utf-8'}).trim();
	} catch {
		return '';
	}
}

const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf-8'));

// Vercel provides the commit it is building; a local run falls back to git.
const commit = (process.env.VERCEL_GIT_COMMIT_SHA || git(['rev-parse', 'HEAD']) || 'unknown').slice(0, 12);
const branch =
	process.env.VERCEL_GIT_COMMIT_REF || git(['rev-parse', '--abbrev-ref', 'HEAD']) || 'unknown';
const built_at = new Date().toISOString();

/**
 * @typedef {object} Download
 * @property {string} label
 * @property {string} detail
 * @property {string} href
 */

/** @type {Download[]} */
const downloads = [
	{
		label: 'Windows 7 SP1 · 64-bit installer',
		detail: 'Built by GitHub Actions, no local toolchain needed',
		// The newest successful run of the Windows workflow. GitHub always
		// redirects this to the run's artifact page.
		href: `https://github.com/${GITHUB_REPO}/actions/workflows/${WORKFLOW_FILE}?query=is%3Asuccess`,
	},
	{
		label: 'Linux · deb and AppImage',
		detail: 'Same version, packaged by electron-builder',
		href: `https://github.com/${GITHUB_REPO}/actions/workflows/build-linux.yml?query=is%3Asuccess`,
	},
];

const build_info = {
	name: 'Blockbench',
	version: pkg.version,
	commit,
	branch,
	built_at,
	repo: `https://github.com/${GITHUB_REPO}`,
	website: 'https://www.blockbench.net',
	downloads,
};

fs.writeFileSync(
	path.join(root, 'build-info.json'),
	JSON.stringify(build_info, null, '\t') + '\n',
	'utf-8'
);

// The landing page is plain HTML, so the data has to arrive as a script rather
// than a fetch, which would fail for anyone opening the built files locally.
const site_js = `// Generated by scripts/site.mjs. Do not edit.
window.SITE = ${JSON.stringify(build_info, null, '\t')};
`;
fs.writeFileSync(path.join(root, 'publisher', 'site.js'), site_js, 'utf-8');

console.log(
	`[site] ${build_info.name} ${build_info.version} (${build_info.commit}, ${build_info.branch}) -> build-info.json, publisher/site.js`
);
